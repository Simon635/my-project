-- Схема базы данных системы ремонта мультимедийного оборудования

DROP TABLE IF EXISTS repair_requests;
DROP TABLE IF EXISTS classrooms;
DROP TABLE IF EXISTS users;

-- Справочник аудиторий
CREATE TABLE classrooms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- Пользователи системы
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('Teacher', 'Dispatcher', 'Technician'))
);

-- Заявки на ремонт
CREATE TABLE repair_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL UNIQUE,
    title VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'New'
        CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    classroom_id INTEGER NOT NULL
        REFERENCES classrooms(id),
    created_by_user_id INTEGER NOT NULL
        REFERENCES users(id),
    assignee_user_id INTEGER
        REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Индекс для фильтрации заявок по статусу
CREATE INDEX idx_repair_requests_status
    ON repair_requests(status);

-- Индекс для поиска заявок по аудитории
CREATE INDEX idx_repair_requests_classroom
    ON repair_requests(classroom_id);

-- Индекс для сортировки заявок по дате создания
CREATE INDEX idx_repair_requests_created_at
    ON repair_requests(created_at DESC);
